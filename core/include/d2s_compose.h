/* Задаёт вопросы о свойствах коробки на настоящей цели, через датапат.
 *
 * link_fd — дескриптор связи, открытый d2s_link_open (задача 4): по нему
 * ставится план (D2S_CMD_SET_NAME), ждётся подтверждение, и читается исход
 * обмена (D2S_EV_EXCHANGE, порог d2s_ev_outer_appdata). ip/port — куда сделать
 * ОДНО обращение (обычным соединением: план манглит его пакеты на пути через
 * датапат, не эта функция). trigger — реально снятое приветствие цели: его
 * же байты идут на провод как есть (§4: приветствие — измерительный прибор,
 * самодельное меряет не ту коробку), и из него же по SNI берётся имя для
 * SET_NAME — датапат матчит план по имени, а не по адресу (d2s_link.h,
 * d2s_link_set_name). control — реально снятое приветствие ДРУГОГО имени на
 * ту же цель; его байты идут ВЕРБАТИМ как содержимое фальшивок вопросов
 * «счёт дубликатов» и «разбор протокола» — тем же приёмом, каким весь этот
 * модуль настаивает на настоящих байтах, а не самодельных (см. шапку
 * compose.c): раз реальный захват уже есть, синтезировать приманку профилем
 * (как делает d2s_compose при отсутствии такого захвата) значило бы
 * заведомо понижать достоверность без всякой причины.
 *
 * mark ПРИНЯТ КОНТРАКТОМ, НО ЭТИМ ЗОНДОМ НЕ ПРИМЕНЯЕТСЯ (ревью 11.09, круг
 * правок 2, находка 2) — до этого здесь стояло «та же метка, что ставит
 * датапат на боевые пакеты», и это было НЕВЕРНО, а не просто неточно:
 * files/S99d2s, ПЕРВОЕ правило исходящей цепочки —
 *     iptables -t mangle -A "$CHAIN_OUT" -m mark --mark "$MARK" -j RETURN
 * — уводит помеченный пакет ДО правила NFQUEUE. Пометь этот зонд той же
 * меткой — план, который d2s_props_ask только что поставил, физически не
 * применится к его пакетам: приветствие уйдёт голым, а любой ответ будет
 * ответом на ГОЛОЕ приветствие, выданным за ответ на приём (тот же класс
 * ошибки, что в docs/field/2026-09-05-active-probe.md, с обратным знаком).
 * §5.5/§7 требуют метку на зондах ДЕРЕВА ВЕРДИКТОВ (d2s_classify) — тому
 * нужна ГОЛАЯ линия, не искажённая уже действующим планом, и метка даёт
 * НЕ поставленному только сейчас плану применяться. Опрос свойств спрашивает
 * обратное — применится ли ЕГО ЖЕ план-кандидат — и метка здесь ломает
 * именно то, что задаётся вопросом. Параметр остаётся в сигнатуре ради
 * единообразия с d2s_classify (тот же контракт связи датапата) и на случай,
 * если у будущего вызывающего заведётся причина отличить зонды между собой,
 * но d2s_props_ask его не читает: соответствующее обращение к цели идёт
 * заведомо непомеченным (см. props_ask_contact, compose.c).
 *
 * Порядок вопросов — ЗЕРКАЛО classify.PropProbes (properties.go): перекрытие
 * слева, счёт дубликатов, порядок сегментов, контрольная сумма, разбор
 * протокола — цена таймаута, не вкус (см. её же комментарий). Первый ПРОШЕДШИЙ
 * вопрос обрывает опрос: это уже стратегия, второй план для той же цели
 * не нужен (тот же принцип, что в controller.go verdictCandidates про
 * "до сбора нескольких подтверждённых свойств дело физически не доходит").
 *
 * ИСХОД ЧИТАЕТСЯ ПО СВОЕМУ ПОТОКУ, А НЕ ПО ЛЮБОМУ ОТВЕТУ ТОГО ЖЕ ВИДА
 * (ревью 11.09, круг правок 2, находка 1). D2S_EV_EXCHANGE — не адресный
 * ответ на команду: датапат присылает его для ЛЮБОГО потока с приветствием
 * и обратной нагрузкой (datapath/session.c), независимо от того, стоит ли
 * на этом имени наш план, и ctlsrv.c проталкивает событие единственному
 * клиенту без фильтрации. На роутере с фоновым HTTPS-трафиком (обычное
 * дело, не край) чужой обмен, пришедший в те же секунды, засчитался бы за
 * ответ на СВОЙ зонд без фильтра по ключу потока — d2s_props_ask сверяет
 * полный ключ (свой адрес:порт против адреса:порта цели), не только вид
 * события (см. wait_for_event/ev_matches_flow, compose.c).
 *
 * Возвращает вектор из одних D2S_P_UNKNOWN, если спросить нечем вовсе:
 * link_fd < 0, ip пуст, у trigger нет байт или нет извлекаемого имени
 * (d2s_hello_sni) — тройственная логика тут та же, что и в остальном ядре:
 * «не измерено» не подделывается «нет»-ом.
 *
 * ДВА ДОЛГА, ОСТАВЛЕННЫЕ ЭТОЙ РЕАЛИЗАЦИЕЙ ОСОЗНАННО — СНЯТЬ В КРУГЕ
 * ПЛАНИРОВЩИКА (задача 5, шаги 1-5), НЕ ЗДЕСЬ:
 *
 * 1. (Закрыт: каждый не прошедший вопрос снимается своим ключом,
 *    DEL_NAME_PROBE по порту вопроса — задача 21; широкого снятия по имени
 *    нет.) Исторически: план ПОСЛЕДНЕГО заданного зонда оставался стоять.
 *    Решение осознанное: у Go снятие плана — дело controller.go (advance()/
 *    clear()), а не classify-слоя, и здесь та же граница ответственности —
 *    но её ОБЯЗАН закрыть тот, кто пишет d2s_sched/d2sc, иначе цель,
 *    признанная неберущейся, останется с чужим планом на линии.
 *
 * 2. D2S_PROPS_ASK_WAIT_MS (compose.c) — ОДНО число и на ack SET_NAME по
 *    локальному AF_UNIX (миллисекунды по природе), и на обмен с целью по
 *    настоящей сети (секунды по природе). Число УНАСЛЕДОВАНО (WAIT_CEIL_MS,
 *    meas.c) — это не то же самое, что ИЗМЕРЕНО ДЛЯ ЭТОГО применения: на
 *    живой линии этот потолок не проверялся ни разу, и если планировщик
 *    увидит настоящие ложные тайм-ауты обмена, чинить нужно ЗДЕСЬ, числом
 *    из замера, а не заново гадать. */
d2s_props d2s_props_ask(int link_fd, const char *ip, uint16_t port,
                        d2s_hello trigger, d2s_hello control, uint32_t mark);

/* Выводит планы из вектора. Возвращает число записанных, максимум cap.
 * Планы — текст формата d2s-plan, как в каталоге (d2s_catalog.h:
 * d2s_cat_plan.text; на Go-стороне — internal/plan.Plan.Text()). Плечо
 * появляется тогда и только тогда, когда соответствующее свойство измерено
 * и говорит, что оно применимо — КРОМЕ полностью неизмеренного вектора: это
 * особый случай с единственным честным планом «всё сразу» (см. compose.c,
 * everything_plan_text, и Go Compose — properties.go:214-221), а не «ничего
 * не выводить». Плечо, которое не поместилось целиком в sizeof(out[0]) байт
 * или не собралось (например, decoy пуст, а план в нём нуждается),
 * пропускается целиком, а не пишется усечённым и не считается в возвращённом
 * числе.
 *
 * target_shape — вид СНЯТОГО приветствия цели (d2s_hello_shape, d2s_hello.h),
 * а не приманки: коробка может по-разному относиться к TLS 1.2 и 1.3 (§6
 * спеки), и приманка вопросов «счёт дубликатов»/«разбор протокола»/«всё
 * сразу» собирается ТЕМ ЖЕ видом — мерить целевую коробку приманкой другого
 * вида значит мерить не то. D2S_SHAPE_UNKNOWN падает на LEGACY (меньший из
 * двух профилей) как безопасный запасной вариант, а не как угаданное «нет»:
 * это выбор ФОРМЫ ПРИМАНКИ, не записываемое свойство коробки, тройственная
 * логика d2s_props этим не затрагивается. */
/* send_cap — предел длины посылки, объявленный датапатом (D2S_EV_PROTO);
 * 0 — не объявлен. Тело фальшивки урезается по нему: оно обязано и покрывать
 * то, что должно покрыть, и помещаться в канал. */
size_t d2s_compose(const d2s_props *pr, d2s_shape target_shape, const char *decoy,
                   size_t send_cap, char out[][4096], size_t cap);

