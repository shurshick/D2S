/* РАЗНОС ПОСЫЛОК ВО ВРЕМЕНИ. Оба числа наследуются от донора замером.
 *
 * D2S_PACE_PIECE_US — пауза между кусками нагрузки при переупорядочивании:
 * z2k-detect шлёт три куска с `time.Sleep(12 * time.Millisecond)` после
 * каждого (raw_linux.go:686-694). Приём про переупорядочивание, исполненный
 * без разноса во времени, переупорядочивания не создаёт: три сегмента уходят
 * одним всплеском, и коробка собирает их как пришедшие подряд.
 *
 * D2S_PACE_SETTLE_US — выдержка между последней фальшивкой и правдой:
 * `time.Sleep(15 * time.Millisecond)` в конце шага 1 probePoison
 * (raw_linux.go:537). Без неё правда догоняет фальшивку в том же всплеске, и
 * коробка видит не ту последовательность, ради которой приём задуман.
 *
 * До 12.09.2026 ни того, ни другого у нас не было вовсе — задержку в языке
 * Plan несла только фальшивка (gap_us между копиями). Побайтная сверка это и
 * показала: docs/decisions/0008-impact-parity.md, расхождения 5 и 6. */
#define D2S_PACE_PIECE_US  12000u
#define D2S_PACE_SETTLE_US 15000u

